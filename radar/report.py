"""End-to-end analysis: diff -> scan -> rank -> draft, plus Markdown rendering and seed scenarios."""

from __future__ import annotations

import json
import time
from pathlib import Path

from radar.differ import diff_specs
from radar.drafter import Drafter, RuleBasedDrafter, make_patch
from radar.models import Change, DocPage, Report, Severity, Summary
from radar.ranker import rank
from radar.scanner import scan_docs

DOC_SUFFIXES = {".md", ".mdx", ".markdown"}
SEVERITY_ICON = {Severity.BREAKING: "🔴", Severity.BEHAVIORAL: "🟠", Severity.ADDITIVE: "🟢"}


class ScenarioNotFound(KeyError):
    pass


def load_docs(docs_dir: Path) -> list[DocPage]:
    docs_dir = Path(docs_dir)
    pages = [
        DocPage(path=p.relative_to(docs_dir).as_posix(), content=p.read_text(encoding="utf-8"))
        for p in sorted(docs_dir.rglob("*"))
        if p.is_file() and p.suffix in DOC_SUFFIXES
    ]
    return pages


def list_scenarios(seed_dir: Path) -> list[dict]:
    return json.loads((Path(seed_dir) / "scenarios.json").read_text())


def load_scenario(seed_dir: Path, scenario_id: str) -> tuple[str, str, list[DocPage]]:
    seed_dir = Path(seed_dir)
    for s in list_scenarios(seed_dir):
        if s["id"] == scenario_id:
            return (
                (seed_dir / s["before"]).read_text(encoding="utf-8"),
                (seed_dir / s["after"]).read_text(encoding="utf-8"),
                load_docs(seed_dir / s["docs_dir"]),
            )
    raise ScenarioNotFound(scenario_id)


def analyze(before: str | dict, after: str | dict, docs: list[DocPage], drafter: Drafter | None = None) -> Report:
    drafter = drafter or RuleBasedDrafter()
    started = time.perf_counter()
    changes = diff_specs(before, after)
    hits = scan_docs(docs, changes) if changes else []
    impacts = rank(hits, changes)
    scan_ms = (time.perf_counter() - started) * 1000
    by_path = {d.path: d for d in docs}
    for impact in impacts:
        page = by_path[impact.path]
        new = drafter.draft(page, impact.hits, changes)
        impact.suggested_patch = make_patch(page.path, page.content, new)
    summary = Summary(
        change_count=len(changes),
        breaking_count=sum(c.severity is Severity.BREAKING for c in changes),
        impacted_pages=len(impacts),
        total_hits=len(hits),
        pages_scanned=len(docs),
        skip_llm=not changes,
        scan_ms=round(scan_ms, 2),
        drafter=getattr(drafter, "name", type(drafter).__name__),
    )
    return Report(changes=changes, impacts=impacts, summary=summary)


def _change_line(c: Change) -> str:
    return f"- {SEVERITY_ICON[c.severity]} **{c.kind.value}** `{c.operation}`: {c.detail}"


def to_markdown(report: Report) -> str:
    """Render the report as a PR comment / PR description."""
    s = report.summary
    out = ["## OpenAPI Drift Radar", ""]
    if not report.changes:
        out += ["✅ No API contract changes in this PR. Skipping the docs agent run (0 LLM tokens).", ""]
        return "\n".join(out)
    out += [
        f"**{s.total_hits} stale references across {s.impacted_pages} pages** "
        f"({s.change_count} contract changes, {s.breaking_count} breaking; {s.pages_scanned} pages scanned "
        f"in {s.scan_ms:.1f} ms).",
        "",
        "### Contract changes",
        "",
        *(_change_line(c) for c in report.changes),
        "",
        "### Impacted pages",
        "",
    ]
    for impact in report.impacts:
        out.append(f"#### `{impact.path}` · {impact.hit_count} hits · score {impact.score}")
        out.append("")
        for h in impact.hits:
            out.append(f"- `{h.path}:{h.line}` ({h.context}, {h.kind.value}): `{h.excerpt}`")
        if impact.suggested_patch:
            out += [
                "",
                "<details><summary>Suggested patch</summary>",
                "",
                "```diff",
                impact.suggested_patch.rstrip("\n"),
                "```",
                "",
                "</details>",
            ]
        out.append("")
    if not report.impacts:
        out += ["No docs pages reference the changed operations.", ""]
    out.append("_Generated by OpenAPI Drift Radar._")
    return "\n".join(out)
